function searchUrl(source, search = {}) {
  const query =
    search.query ||
    search.keywords?.split(",")[0]?.trim() ||
    "computer science";
  const location =
    search.countries?.length === 1
      ? search.countries[0]
      : source.countries?.length === 1
        ? source.countries[0]
        : source.region === "Gulf"
          ? "Middle East"
          : source.region === "All"
            ? ""
            : source.region;
  const route = source.template
    ? source.template
        .replaceAll("{q}", encodeURIComponent(query))
        .replaceAll(
          "{slug}",
          encodeURIComponent(
            query
              .toLowerCase()
              .replace(/[^a-z0-9]+/g, "-")
              .replace(/^-|-$/g, ""),
          ),
        )
        .replaceAll("{location}", encodeURIComponent(location))
    : source.publicIndex
      ? "/"
      : source.query + encodeURIComponent(query);
  return source.base + route;
}
function sourceMatches(source, search) {
  return (
    source.region === "All" ||
    (source.countries
      ? source.countries.some((c) => search.countries.includes(c))
      : search.countries.some((c) =>
          require("./core.cjs").COUNTRIES[source.region]?.includes(c),
        ))
  );
}
